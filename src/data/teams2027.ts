export const getCustomKitsFromStorage = (): Record<string, KitConfig> => {
  try {
    const raw = localStorage.getItem('arenabola_custom_kits_v1');
    if (!raw) return {};
    return JSON.parse(raw);
  } catch {
    return {};
  }
};

export const saveCustomKitToStorage = (teamId: string, kit: KitConfig) => {
  const existing = getCustomKitsFromStorage();
  existing[teamId] = kit;
  localStorage.setItem('arenabola_custom_kits_v1', JSON.stringify(existing));
};

export const getTeamsWithCustomKits = (): Team[] => {
  const custom = getCustomKitsFromStorage();
  return INITIAL_TEAMS_2027.map((team) =>
    custom[team.id] ? { ...team, kit: custom[team.id] } : team
  );
};

-- 4. Funções auxiliares de segurança (evitam recursão nas policies RLS)
create or replace function public.is_super_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.jogadores
    where user_id = auth.uid()
      and role = 'super_admin'
  );
$$;

create or replace function public.is_admin_or_super()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.jogadores
    where user_id = auth.uid()
      and role in ('admin', 'super_admin')
  );
$$;

-- Verifica se já existe pelo menos um Super Admin cadastrado (usado no setup inicial seguro)
create or replace function public.has_any_super_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.jogadores where role = 'super_admin'
  );
$$;

-- Permite que o primeiro usuário autenticado reivindique Super Admin APENAS se ainda não houver nenhum
create or replace function public.claim_initial_super_admin()
returns public.jogadores
language plpgsql
security definer
set search_path = public
as $$
declare
  caller_id uuid := auth.uid();
  updated_row public.jogadores;
begin
  if caller_id is null then
    raise exception 'Usuário não autenticado.';
  end if;

  if exists (select 1 from public.jogadores where role = 'super_admin') then
    raise exception 'Já existe um Super Admin configurado no projeto.';
  end if;

  update public.jogadores
     set role = 'super_admin',
         updated_at = now()
   where user_id = caller_id
  returning * into updated_row;

  if updated_row.id is null then
    raise exception 'Perfil do jogador não encontrado.';
  end if;

  return updated_row;
end;
$$;

-- Permite apenas a um Super Admin alterar o cargo de outros usuários
create or replace function public.admin_set_user_role(target_user_id uuid, new_role text)
returns public.jogadores
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_row public.jogadores;
begin
  if not public.is_super_admin() then
    raise exception 'Apenas Super Admins podem alterar cargos de usuários.';
  end if;

  if new_role not in ('user', 'admin', 'super_admin') then
    raise exception 'Cargo inválido.';
  end if;

  update public.jogadores
     set role = new_role,
         updated_at = now()
   where user_id = target_user_id
  returning * into updated_row;

  if updated_row.id is null then
    raise exception 'Usuário alvo não encontrado.';
  end if;

  return updated_row;
end;
$$;

-- Ranking público seguro (sem expor e-mail nem JSON de carreira privada)
create or replace function public.get_public_leaderboard(limit_rows int default 30)
returns table (
  id bigint,
  user_id uuid,
  nome text,
  time_favorito text,
  moedas bigint,
  vitorias bigint,
  empates bigint,
  derrotas bigint,
  gols bigint,
  gols_sofridos bigint
)
language sql
security definer
stable
set search_path = public
as $$
  select
    j.id,
    j.user_id,
    j.nome,
    j.time_favorito,
    j.moedas,
    j.vitorias,
    j.empates,
    j.derrotas,
    j.gols,
    j.gols_sofridos
  from public.jogadores j
  order by (j.vitorias * 3 + j.empates) desc, j.vitorias desc, (j.gols - j.gols_sofridos) desc, j.gols desc
  limit greatest(1, least(limit_rows, 100));
$$;

-- Trigger para impedir que um usuário comum altere seu próprio cargo via UPDATE direto
create or replace function public.protect_jogadores_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  if old.role is distinct from new.role and not public.is_super_admin() then
    new.role := old.role;
  end if;
  if old.user_id is distinct from new.user_id then
    new.user_id := old.user_id;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_protect_jogadores_role on public.jogadores;
create trigger trg_protect_jogadores_role
before update on public.jogadores
for each row execute function public.protect_jogadores_role();

-- Trigger automática: cria o perfil em public.jogadores ao cadastrar no Supabase Auth
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  meta_nome text := coalesce(nullif(trim(new.raw_user_meta_data->>'nome'), ''), split_part(coalesce(new.email, 'Jogador'), '@', 1));
  meta_team text := coalesce(nullif(trim(new.raw_user_meta_data->>'time_favorito'), ''), 'fla');
begin
  insert into public.jogadores (user_id, email, nome, time_favorito, role, moedas, vitorias, gols, carreira)
  values (new.id, new.email, left(meta_nome, 28), meta_team, 'user', 100, 0, 0, '{"trophies":[]}'::jsonb)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

-- 5. Habilita Row Level Security (RLS) com separação total por usuário
alter table public.jogadores enable row level security;
alter table public.salas_online enable row level security;
alter table public.partidas_2p enable row level security;

-- Policies de public.jogadores
drop policy if exists "jogadores_select_own_or_admin" on public.jogadores;
create policy "jogadores_select_own_or_admin"
  on public.jogadores for select
  to authenticated
  using (auth.uid() = user_id or public.is_admin_or_super());

drop policy if exists "jogadores_insert_own" on public.jogadores;
create policy "jogadores_insert_own"
  on public.jogadores for insert
  to authenticated
  with check (auth.uid() = user_id and role = 'user');

drop policy if exists "jogadores_update_own_or_super" on public.jogadores;
create policy "jogadores_update_own_or_super"
  on public.jogadores for update
  to authenticated
  using (auth.uid() = user_id or public.is_super_admin())
  with check (auth.uid() = user_id or public.is_super_admin());

-- Policies de public.salas_online
drop policy if exists "salas_select_authenticated" on public.salas_online;
create policy "salas_select_authenticated"
  on public.salas_online for select
  to authenticated
  using (true);

drop policy if exists "salas_insert_host" on public.salas_online;
create policy "salas_insert_host"
  on public.salas_online for insert
  to authenticated
  with check (auth.uid() = host_user_id);

drop policy if exists "salas_update_participants" on public.salas_online;
create policy "salas_update_participants"
  on public.salas_online for update
  to authenticated
  using (
    auth.uid() = host_user_id
    or auth.uid() = guest_user_id
    or (status = 'waiting' and guest_user_id is null)
  )
  with check (
    auth.uid() = host_user_id
    or auth.uid() = guest_user_id
  );

drop policy if exists "salas_delete_host" on public.salas_online;
create policy "salas_delete_host"
  on public.salas_online for delete
  to authenticated
  using (auth.uid() = host_user_id);

-- Policies de public.partidas_2p
drop policy if exists "partidas_select_authenticated" on public.partidas_2p;
create policy "partidas_select_authenticated"
  on public.partidas_2p for select
  to authenticated
  using (true);

drop policy if exists "partidas_insert_authenticated" on public.partidas_2p;
create policy "partidas_insert_authenticated"
  on public.partidas_2p for insert
  to authenticated
  with check (auth.uid() = player1_user_id or auth.uid() = player2_user_id);


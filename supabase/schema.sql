-- 1. Tabela principal de jogadores (vinculada a auth.users com dados separados por usuário)
create table if not exists public.jogadores (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete cascade,
  email text,
  nome text not null,
  time_favorito text not null default 'fla',
  role text not null default 'user' check (role in ('user', 'admin', 'super_admin')),
  moedas bigint not null default 100,
  vitorias bigint not null default 0,
  empates bigint not null default 0,
  derrotas bigint not null default 0,
  gols bigint not null default 0,
  gols_sofridos bigint not null default 0,
  carreira jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Caso a tabela "jogadores" já exista de versões anteriores, garante as novas colunas:
alter table public.jogadores add column if not exists user_id uuid unique references auth.users(id) on delete cascade;
alter table public.jogadores add column if not exists email text;
alter table public.jogadores add column if not exists role text not null default 'user';
alter table public.jogadores add column if not exists empates bigint not null default 0;
alter table public.jogadores add column if not exists derrotas bigint not null default 0;
alter table public.jogadores add column if not exists gols_sofridos bigint not null default 0;
alter table public.jogadores add column if not exists created_at timestamptz not null default now();
alter table public.jogadores add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'jogadores_role_check'
  ) then
    alter table public.jogadores
      add constraint jogadores_role_check check (role in ('user', 'admin', 'super_admin'));
  end if;
end $$;

create index if not exists idx_jogadores_user_id on public.jogadores(user_id);
create index if not exists idx_jogadores_email on public.jogadores(lower(email));

-- 2. Tabela de salas online 2P
